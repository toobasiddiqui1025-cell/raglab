"""RAG pipeline answer generation and orchestration module.

Coordinates retrieval of relevant paper chunks, prompt construction, LLM generation,
citation parsing, and latency/token usage tracking into structured answers.
"""

from typing import List, Optional
from pydantic import BaseModel
from raglab.generation.llm import LLMClient
from raglab.indexing.vector_store import SearchResult


class Citation(BaseModel):
    """Represents an extracted source citation within an answer.

    Attributes:
        doc_id: Source paper identifier.
        page_number: Source paper page number cited.
    """
    doc_id: str
    page_number: int


class RAGAnswer(BaseModel):
    """Structured response returned by the RAG answerer pipeline.

    Attributes:
        question: Original query submitted by user.
        answer: Generated answer text.
        citations: Extracted source citations.
        retrieved_chunks: Chunks retrieved by the retrieval pipeline.
        latency_seconds: Total pipeline execution latency in seconds.
        prompt_tokens: Number of prompt tokens used by the LLM.
        completion_tokens: Number of completion tokens generated by the LLM.
        total_tokens: Total token count consumed.
    """
    question: str
    answer: str
    citations: List[Citation]
    retrieved_chunks: List[SearchResult]
    latency_seconds: float
    prompt_tokens: int = 0
    completion_tokens: int = 0
    total_tokens: int = 0


class RAGAnswerer:
    """Orchestrates end-to-end question answering over research papers."""

    def __init__(self, retriever: object, llm_client: LLMClient) -> None:
        """Initialize pipeline with configured retriever and LLM client.

        Args:
            retriever: Configured retriever instance (dense, sparse, or hybrid).
            llm_client: Configured LLMClient instance (GeminiClient or MockLLMClient).
        """
        pass

    def answer(self, question: str, top_k: int = 5) -> RAGAnswer:
        """Generate a grounded, cited answer for a user question.

        Args:
            question: User inquiry text.
            top_k: Number of context chunks to retrieve.

        Returns:
            RAGAnswer: Structured answer with citations and execution telemetry.
        """
        raise NotImplementedError
